local L, current = {}, T.en
ns.L = L
setmetatable(L, { __index = function(_, k) return current[k] or T.en[k] or k end })

function ns.setLanguage(lang)
  ns.lang = (lang == "es") and "es" or "en"
  current = T[ns.lang]
end

-- "auto" sigue al cliente: espanol si el cliente es esES o esMX, ingles en cualquier otro caso.
function ns.detectLanguage(pref)
  if pref == "es" or pref == "en" then return pref end
  local locale = GetLocale and GetLocale() or "enUS"
  return (locale:sub(1, 2) == "es") and "es" or "en"
end

-- 12345.6 -> "12.346" (es) o "12,346" (en)
function ns.fmt(n)
  local sep = L.thousands
  local s = tostring(math.floor((n or 0) + 0.5))
  return (s:reverse():gsub("(%d%d%d)", "%1" .. sep):reverse():gsub("^%" .. sep, ""))
end

